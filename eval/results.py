#!/usr/bin/env python3
"""Roll every scored run up into one table, from the raw files.

`eval/data/` is gitignored, so until now every number this project published
lived only in a doc — the run that produced it was on somebody's disk and
nowhere else. Re-answering "what was bm25 R@5 on the kernel again?" meant
re-running a two-hour job, and §13.7 shows what happens when nobody can check:
a figure stops reproducing and there is no way to tell whether the engine, the
corpus or the harness moved.

So: `eval/results/` is tracked. It holds the raw per-query ranks — which is
what paired statistics need, and what an aggregate can never be recovered
from — and this script derives INDEX.md from them. The index is generated,
never hand-edited; if it disagrees with the JSON, the JSON is right.

    python3 eval/results.py            # regenerate INDEX.md and index.json
    python3 eval/results.py --check    # fail if INDEX.md is out of date

Total cost of keeping all of it: well under 1 MB.
"""

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import leakage  # noqa: E402

HERE = Path(__file__).parent
RESULTS = HERE / "results"
LEGACY = HERE / "data"
METRICS = ("recall@1", "recall@5", "recall@10", "mrr@10")


def load_all():
    """Every result file, newest layout first. Returns [(name, rows)]."""
    out = []
    for d in (RESULTS, LEGACY):
        if not d.is_dir():
            continue
        for p in sorted(d.glob("*.json")):
            if p.name in ("index.json", "MANIFEST.json"):
                continue
            try:
                rows = json.loads(p.read_text())
            except (json.JSONDecodeError, OSError):
                continue
            if isinstance(rows, list) and rows and isinstance(rows[0], dict) \
                    and "mode" in rows[0]:
                out.append((p.stem, rows))
    # de-dupe by stem, preferring eval/results over eval/data
    seen, uniq = set(), []
    for name, rows in out:
        if name not in seen:
            seen.add(name)
            uniq.append((name, rows))
    return uniq


def run_meta(rows):
    """Provenance, or a marker saying it was not recorded. Never invented."""
    for r in rows:
        if isinstance(r.get("run"), dict):
            return r["run"]
    return None


def _query_sets_by_fp():
    """queries_fp -> query set name, from eval/queries/MANIFEST.json."""
    mf = HERE / "queries" / "MANIFEST.json"
    if not mf.exists():
        return {}
    try:
        m = json.loads(mf.read_text())
    except (json.JSONDecodeError, OSError):
        return {}
    return {v["queries_fp"]: name for name, v in m.items() if v.get("queries_fp")}


def resolve_query_set(fp, by_fp):
    """Which query set produced this run, RECOVERED not guessed.

    Runs predating provenance still stamped `queries_fp`, a sha256 of the
    query file. Matching it against the checked-in sets identifies the set
    from evidence in the data. A fingerprint that matches nothing means the
    set is gone or was never checked in, and that is reported as such rather
    than left blank.
    """
    if not fp:
        return None
    return by_fp.get(fp, f"unknown (fp {fp})")


def summarize(name, rows, by_fp=None):
    meta = run_meta(rows)
    by_fp = by_fp or {}
    cells = []
    for r in rows:
        if "recall@5" not in r:
            continue
        cells.append({
            "mode": r["mode"], "kind": r["kind"], "n": r.get("n"),
            **{m: r.get(m) for m in METRICS},
            "has_ranks": bool(r.get("ranks")),
        })
    return {
        "name": name,
        "n_cells": len(cells),
        "n_ranks": sum(len(r.get("ranks") or []) for r in rows),
        "corpus": (meta or {}).get("corpus"),
        "queries": (meta or {}).get("queries"),
        "queries_fp": (meta or {}).get("queries_fp") or rows[0].get("queries_fp"),
        "query_set": resolve_query_set(
            (meta or {}).get("queries_fp") or rows[0].get("queries_fp"), by_fp),
        "corpus_digest": (meta or {}).get("corpus_digest"),
        "at": (meta or {}).get("at"),
        "git_head": (meta or {}).get("git_head"),
        "binary_mtime": (meta or {}).get("binary_mtime"),
        "provenance_recorded": meta is not None,
        "cells": cells,
    }


def _is_blind_run(s):
    """A run belongs to the blind board when any of its cells scored a
    §15-gated kind. Membership is derived from the scored data, never from
    the filename."""
    return any(c["kind"] in leakage.BLIND_KINDS for c in s["cells"])


def _is_guess_run(s):
    """The §16 primary board: cells scored on real agentic guesses."""
    return any(c["kind"] in leakage.GUESS_KINDS for c in s["cells"])


def render(summaries):
    L = ["# eval/results — every scored run, rolled up",
         "",
         "**Generated by `python3 eval/results.py`. Do not hand-edit.**",
         "The per-query ranks in the JSON files are the source of truth; this",
         "is a view of them. `--check` fails if the two have diverged.",
         "",
         f"{len(summaries)} runs, "
         f"{sum(s['n_ranks'] for s in summaries):,} per-query ranks recorded.",
         ""]

    def run_table(subset):
        rows = ["| run | query set | corpus | cells | ranks | when | git | provenance |",
                "|---|---|---|---|---|---|---|---|"]
        for s in sorted(subset, key=lambda s: (s["at"] or "", s["name"]), reverse=True):
            prov = "yes" if s["provenance_recorded"] else "**not recorded**"
            qs = s["query_set"] or "—"
            rows.append(f"| `{s['name']}` | {qs} | {s['corpus'] or '—'} | {s['n_cells']} | "
                        f"{s['n_ranks']:,} | {(s['at'] or '—')[:10]} | "
                        f"{s['git_head'] or '—'} | {prov} |")
        return rows

    guess = [s for s in summaries if _is_guess_run(s)]
    blind = [s for s in summaries if not _is_guess_run(s) and _is_blind_run(s)]
    named = [s for s in summaries
             if not _is_guess_run(s) and not _is_blind_run(s)]
    if guess:
        L += ["## Runs — guess (primary, RESEARCH.md §16)", ""]
        L += run_table(guess)
        L += [""]
    if blind:
        L += ["## Runs — blind (model-experiment instrument, RESEARCH.md §15.10)", ""]
        L += run_table(blind)
        L += [""]
    L += ["## Runs — named-identifier (regression)" if (blind or guess) else "## Runs", ""]
    L += run_table(named)

    L += ["", "## Every metric, every run", "",
          "| run | mode | kind | n | R@1 | R@5 | R@10 | MRR@10 |",
          "|---|---|---|---|---|---|---|---|"]
    for s in sorted(summaries, key=lambda s: s["name"]):
        for c in s["cells"]:
            vals = " | ".join(
                f"{c[m]:.3f}" if isinstance(c[m], (int, float)) else "—"
                for m in METRICS)
            L.append(f"| `{s['name']}` | {c['mode']} | {c['kind']} | "
                     f"{c['n'] or '—'} | {vals} |")

    missing = [s["name"] for s in summaries if not s["provenance_recorded"]]
    if missing:
        L += ["", "## Runs with no provenance", "",
              "These predate provenance recording. The numbers are real; which",
              "binary and which corpus tree produced them is **not recoverable**",
              "and is not guessed at. Treat them as historical.", ""]
        L += [f"- `{n}`" for n in sorted(missing)]
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="exit non-zero if INDEX.md is stale")
    a = ap.parse_args()

    runs = load_all()
    if not runs:
        raise SystemExit(f"no result files found in {RESULTS} or {LEGACY}")
    by_fp = _query_sets_by_fp()
    summaries = [summarize(n, r, by_fp) for n, r in runs]
    md = render(summaries)

    RESULTS.mkdir(parents=True, exist_ok=True)
    idx_md, idx_json = RESULTS / "INDEX.md", RESULTS / "index.json"
    if a.check:
        if not idx_md.exists() or idx_md.read_text() != md:
            print("INDEX.md is out of date — run `python3 eval/results.py`")
            return 1
        print(f"INDEX.md up to date ({len(runs)} runs)")
        return 0
    idx_md.write_text(md)
    idx_json.write_text(json.dumps(summaries, indent=2) + "\n")
    print(f"wrote {idx_md} and {idx_json}: {len(runs)} runs, "
          f"{sum(s['n_ranks'] for s in summaries):,} per-query ranks")
    n_missing = sum(1 for s in summaries if not s["provenance_recorded"])
    if n_missing:
        print(f"  note: {n_missing} runs carry no provenance (they predate it) — "
              f"listed at the end of INDEX.md rather than silently included")
    return 0


if __name__ == "__main__":
    sys.exit(main())
